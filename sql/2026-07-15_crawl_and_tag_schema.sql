-- =====================================================================
-- 1. クロール先URLテーブル
-- =====================================================================
create table public.crawl_targets (
    -- 2.1 基本情報
    crawl_target_id          text primary key,
    target_name              text not null,
    target_url               text not null,
    domain                   text not null,
    publisher_name           text not null,
    publisher_major          text not null,
    publisher_minor          text,

    -- 2.2 ソースタグ
    theme_major              text,
    theme_minor               text,
    cross_tags                text,
    subject_major             text,
    subject_minor             text,
    region_major               text,
    region_minor                text,
    article_type_major          text,
    article_type_minor           text,
    materiality_tags             text,
    information_attribute         text,

    -- 2.3 クロール仕様
    endpoint_type              text not null,
    crawl_method               text not null,
    change_detection_method    text not null,
    crawl_detail_pages         boolean not null,
    include_paths              text,
    exclude_paths              text,
    search_conditions          text,
    keyword_filters            text,
    javascript_required        boolean,
    authentication_required    boolean,
    pagination_method          text,
    lookback_days              integer,
    fallback_url               text,
    crawl_notes                text,

    -- 2.4 管理情報
    created_at                timestamptz not null default now(),
    updated_at                timestamptz not null default now(),
    notes                     text
);

-- 備考（設計判断）:
--  * crawl_target_id は「文字列」指定のため text 主キー。デフォルト採番なし
--    （発行方法は運用側で決定。UUID採番したい場合は
--     default gen_random_uuid()::text を追加）。
--  * target_url に unique 制約は付けていない
--    （今回はURLの重複処理を行わない方針のため）。
--  * ドメイン/発信主体のマスターテーブルは作成していない
--    （domain, publisher_* はすべてこのテーブル内の自由入力列）。


-- =====================================================================
-- 2. クロールログテーブル
-- =====================================================================
create table public.crawl_logs (
    crawl_log_id      text primary key,
    crawl_target_id   text not null references public.crawl_targets(crawl_target_id),
    started_at        timestamptz not null,
    finished_at       timestamptz,
    run_result        text not null
        check (run_result in ('成功', '一部成功', '失敗', '更新なし')),
    process_stage     text,
    http_status       integer,
    final_url         text,
    items_detected    integer not null,
    new_items         integer not null,
    updated_items     integer not null,
    error_category    text,
    error_message     text,
    retry_count       integer not null,
    crawler_version   text,
    notes             text
);

-- 備考（設計判断）:
--  * run_result は指定された4種類のみを許可するCHECK制約を付けた
--    （データ整合性のための制約であり、「管理項目を増やす」ものではない）。
--  * クロール先ごとの最終成功日時・連続失敗回数・成功率等は、
--    このテーブルを集計して算出する想定（crawl_targets側には持たせない）。


-- =====================================================================
-- 3. タグリファレンステーブル
-- =====================================================================
create table public.tag_reference (
    tag_id       text primary key,
    tag_axis     text not null
        check (tag_axis in ('テーマ', '横断', '主体', '地域', '記事種別', 'マテリアリティ接続', '情報属性')),
    tag_major    text not null,
    tag_minor    text,
    tag_meaning  text not null,
    tag_criteria text not null,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    notes        text
);

-- 備考（設計判断）:
--  * 7つのタグ軸（テーマ／横断／主体／地域／記事種別／マテリアリティ接続／情報属性）
--    を1つのテーブルにtag_axisで区別して格納する構成（軸ごとに別テーブルにはしていない）。
--  * テーマタグは「大分類＞小分類」の2階層。横断タグ・マテリアリティ接続タグは
--    小分類を持たないため tag_minor は NULL。
--  * 主体タグ・地域タグの tag_minor は「代表例」であり網羅的な列挙ではない
--    （notesにその旨を記載）。
--  * 記事種別タグ・情報属性タグは、本文中に3.1〜3.9のテーマのような
--    大分類～小分類の詳細な列挙が無かったため、本文中の言及例から
--    少数のみ推定してシードしている（notesに推定である旨を記載）。
--    正式な分類が定まったら差し替え・追加が必要。
--  * このテーブル自体には記事タグは記録しない
--    （クロール先タグ・タグリファレンスと、記事に付与する記事タグは別物）。


