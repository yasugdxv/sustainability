-- =====================================================================
-- 競合サステナビリティモニタリング: 目標データへのtitle追加
-- 作成日: 2026-07-27（2026-07-27〜2026-07-27eの後に実行する）
--
-- 背景:
--   これまでは「企業×レコード種別(TARGET/KPI/ACTUAL/ESG_RATING)ごとに現行版1件」を
--   前提に、新しく抽出したレコードを常に直近の現行版1件とだけ比較していた。しかし実際には
--   1社が同じ種別で複数の異なるテーマの目標（例: 水・エネルギー・GHG・農業支援等）を
--   同時に持つのが通常であり、無関係な目標同士を比較して「別目標」という紛らわしい
--   変更イベントが大量発生していた。
--
--   competitor_change_detector.py を、新規抽出レコードをまず全ての現行版候補と
--   LLMで突き合わせ、同一の目標とみなせるものがあればそれとだけ差分判定し、
--   無ければ（他の現行版とは無関係に）新規として登録する方式に変更する。
--   本マイグレーションは、その突き合わせ時にLLMへ渡す短い識別ラベルとして
--   title列を追加する（分類時にLLMが生成したレコードの見出しをそのまま保存）。
-- =====================================================================

alter table public.competitor_target_records
    add column if not exists title text;

comment on column public.competitor_target_records.title is
    'competitor_classifier.classify_and_extractが生成したレコードの見出し。'
    '同一目標かどうかをLLMで突き合わせる際の識別ラベルとして使う';
