-- サステナ目標カテゴリ（新規テーブル）
-- 出典: ユーザー提供資料「260728_競合目標DB_サブタグ定義_v0.1.xlsx」の「サブタグ定義」シート。
-- 競合企業の目標・KPI・取組事例が「どんな種類の目標か」を分類する軸で、記事の
-- tag_reference（テーマ軸の小分類=ニューストピック分類）とは目的が異なる別体系のため
-- 意図的に独立したテーブルとして新設する（filter_keywordsを新設した際と同じ考え方）。
--
-- 運用原則（資料より）: 1レコード＝1目標カテゴリ（主目的で判定、多重付与しない）。
-- 「責任あるマーケティング」はサブタグ定義が資料に無いため「その他」1件のみ新設する。
--
-- 実行前提: このファイルはユーザーがSupabase側で手動実行する。

create table public.goal_categories (
    goal_category_id  text primary key,
    major_theme       text not null,
    code              text not null,
    name              text not null,
    definition        text not null,
    display_order     integer,
    status            text not null default '有効'
        check (status in ('有効', '無効')),

    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),

    unique (major_theme, name)
);

create index goal_categories_status_idx on public.goal_categories(status);
create index goal_categories_theme_idx on public.goal_categories(major_theme);

create trigger goal_categories_set_updated_at
    before update on public.goal_categories
    for each row execute function public.set_updated_at();

alter table public.goal_categories enable row level security;

